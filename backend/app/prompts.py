from .schemas import Style

SYSTEM_PROMPT = """Ти пишеш короткі привітання з днем народження українською мовою.

Правила:
- 2–5 речень, без заголовків, лапок і пояснень — лише сам текст привітання.
- Обовʼязково звернись до іменинника на імʼя.
- Гумор має бути добрим: жодних жартів про зовнішність, вагу, вік як недолік,
  національність, здоровʼя, релігію чи орієнтацію. Привітання не повинно ображати.
- Без нецензурної лексики.
"""

STYLE_HINTS: dict[Style, str] = {
    Style.brainrot: (
        "Стиль «брейнрот»: абсурдний інтернет-гумор, меми, сленг на кшталт "
        "«скібіді», «сігма», «різз», «аура +1000», хаотичні порівняння й емодзі."
    ),
    Style.warm: (
        "Стиль «душевно»: теплі щирі побажання, як від близького друга, "
        "трохи легкого гумору, кілька доречних емодзі."
    ),
    Style.official: (
        "Стиль «офіційно»: ввічливо й урочисто, як від колективу чи керівника, "
        "без сленгу й емодзі, але з легкою іронією."
    ),
}


def build_user_prompt(name: str, style: Style) -> str:
    return f"Імʼя іменинника: {name.strip()}\n{STYLE_HINTS[style]}\nНапиши привітання."
